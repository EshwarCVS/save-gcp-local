"""Astro CLI project scaffolding for save-gcp-local.

``save-gcp-local init-astro`` generates (or patches) all the files needed
so that ``astro dev start`` boots an Airflow that automatically intercepts
Dataproc operators and runs Spark jobs locally.

Generated / modified files:
  Dockerfile                         adds Java + Spark + save-gcp-local
  .env                               DPL_* config vars
  plugins/save_gcp_local_plugin.py   auto-loads patching at Airflow startup
  docker-compose.override.yml        local PostgreSQL + optional services
  include/local_connections.json     connection overrides for local services
"""

