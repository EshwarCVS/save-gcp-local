DOCKERFILE_APPEND = """\
# ── save-gcp-local: local Spark execution ─────────────────────────
# Install Java (required by Spark) and download Apache Spark.
USER root
RUN apt-get update && \\
    apt-get install -y --no-install-recommends openjdk-17-jre-headless procps && \\
    rm -rf /var/lib/apt/lists/*

ENV JAVA_HOME=/usr/lib/jvm/java-17-openjdk-amd64
ENV SPARK_HOME=/opt/spark
ENV PATH="${SPARK_HOME}/bin:${PATH}"

ARG SPARK_VERSION=3.5.3
ARG HADOOP_VERSION=3
RUN curl -fsSL "https://archive.apache.org/dist/spark/spark-${SPARK_VERSION}/spark-${SPARK_VERSION}-bin-hadoop${HADOOP_VERSION}.tgz" \\
    | tar -xz -C /opt && \\
    mv "/opt/spark-${SPARK_VERSION}-bin-hadoop${HADOOP_VERSION}" "${SPARK_HOME}"

# Install the framework.
RUN pip install --no-cache-dir "save-gcp-local[all]"
# Install early-patch so Airflow 2.x and 3.x both work.
RUN save-gcp-local install-airflow3 || true

USER astro
# ── end save-gcp-local ────────────────────────────────────────────
"""

